"""Author text options for every block, container item and section (Universal Editor).

Reads tools/text-options/options.json and writes:
  - the "Text style" tab into every block / item model (blocks/*/_*.json, fields `classes_<key>`:
    Universal Editor renders their values as classes on the block or item) and into the section
    model (models/_section.json, fields `<key>`: rendered as section metadata, turned into
    classes by scripts.js); container blocks without a model get one holding only the tab;
  - styles/text-options.css: each option class sets a CSS variable (the nearest block, item or
    section that sets it wins) and one rule per property applies it to the text inside, with an
    id-level specificity (:not(#opt)) so an author's choice beats the blocks' own typography;
  - scripts/text-options.js: the section option keys and class prefixes for scripts.js.
Idempotent: re-running replaces the generated fields. Then run `npm run build:json`.
usage: python3 tools/text-options/build.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CFG = json.load(open(os.path.join(ROOT, 'tools/text-options/options.json')))
PALETTE = CFG['palette']
GROUPS = CFG['groups']
OVERLAY_MODELS = set(CFG['overlay']['models'])
OVERLAY_CONTENT = CFG['overlay']['content']
SKIP = set(CFG['skipModels'])

HEADINGS = 'h1, h2, h3, h4, h5, h6'
BODY = 'p, li, dt, dd, blockquote, cite, label, figcaption, td, th, caption'
TEXT = f'{HEADINGS}, {BODY}'
INLINE = 'span:not(.ico), strong, em, b, i, small, u, sub, sup'
SOFT_INLINE = 'a:not(.button), span:not(.ico)'


def slug(text):
    return ''.join(c.lower() if c.isalnum() else '-' for c in text).strip('-').replace('--', '-')


def options(group):
    if group.get('palette'):
        return [[name, slug(name), value] for name, value in PALETTE.items()]
    return group['options']


def cls(group, opt):
    return f"{group['prefix']}-{opt[1]}"


def scope(group):
    return ':is(' + ', '.join(f'.{cls(group, o)}' for o in options(group)) + '):not(#opt)'


# ---------------------------------------------------------------- models
def tab(name, label):
    return {'component': 'tab', 'label': label, 'name': name}


def fields(section=False, overlay=False):
    out = [tab('text-style-tab', 'Text style')]
    for g in GROUPS:
        if g.get('overlay') and (section or not overlay):
            continue
        out.append({
            'component': 'select',
            'name': g['key'] if section else f"classes_{g['key']}",
            'label': g['label'],
            'valueType': 'string',
            'value': '',
            'options': [{'name': 'Default', 'value': ''}] + [{'name': o[0], 'value': cls(g, o)} for o in options(g)],
        })
    return out


GENERATED = {'text-style-tab', 'content-tab'} | {g['key'] for g in GROUPS} | {f"classes_{g['key']}" for g in GROUPS}


def with_style(model_fields, section=False, overlay=False):
    kept = [f for f in model_fields if f.get('name') not in GENERATED]
    content = [tab('content-tab', 'Content')] if kept else []
    return content + kept + fields(section, overlay)


def dump(path, data, indent):
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, indent=indent, ensure_ascii=False)
        fh.write('\n')


changed = []
for path in sorted(glob.glob(os.path.join(ROOT, 'blocks/*/_*.json'))):
    data = json.load(open(path))
    model_ids = {m['id'] for m in data.get('models', [])}
    for d in data.get('definitions', []):
        tpl = d.get('plugins', {}).get('xwalk', {}).get('page', {}).get('template', {})
        # container blocks: give the container its own model (style fields only)
        if tpl.get('filter') and not tpl.get('model') and d['id'] not in SKIP:
            tpl['model'] = d['id']
            if d['id'] not in model_ids:
                data.setdefault('models', []).append({'id': d['id'], 'fields': []})
                model_ids.add(d['id'])
    for m in data.get('models', []):
        if m['id'] in SKIP:
            continue
        m['fields'] = with_style(m['fields'], overlay=m['id'] in OVERLAY_MODELS)
    dump(path, data, 2)
    changed.append(os.path.relpath(path, ROOT))

sec_path = os.path.join(ROOT, 'models/_section.json')
sec = json.load(open(sec_path))
for m in sec['models']:
    if m['id'] == 'section':
        m['fields'] = with_style(m['fields'], section=True)
dump(sec_path, sec, 1)
changed.append('models/_section.json')

# ---------------------------------------------------------------- CSS
css = ['/* GENERATED by tools/text-options/build.py from tools/text-options/options.json — do not edit.',
       '   Author text options (Universal Editor "Text style" tab on every block, item and section).',
       '   Each option class sets a variable; the nearest scope that sets it wins. The apply rules carry',
       '   an id-level specificity (:not(#opt)) so an explicit author choice beats block typography. */', '']
for g in GROUPS:
    if g.get('overlay'):
        continue
    css.append(f"/* {g['label']} */")
    for o in options(g):
        if g.get('var2'):
            css.append(f".{cls(g, o)} {{\n  {g['var']}: {o[2]};\n  {g['var2']}: {o[3]};\n}}\n")
        else:
            css.append(f".{cls(g, o)} {{ {g['var']}: {o[2]}; }}")
    css.append('')
wide = [(g, o) for g in GROUPS if g.get('var2') for o in options(g) if len(o) > 4]
if wide:
    css.append('@media (width >= 900px) {')
    for g, o in wide:
        css.append(f"  .{cls(g, o)} {{\n    {g['var']}: {o[4]};\n    {g['var2']}: {o[5]};\n  }}\n")
    css += ['}', '']

G = {g['key']: g for g in GROUPS}


def rule(selectors, decls):
    css.append(',\n'.join(selectors) + ' {')
    css.extend(f'  {d}' for d in decls)
    css.extend(['}', ''])


s = scope(G['font'])
rule([s, f'{s} *'], ['font-family: var(--opt-ff);'])
s = scope(G['headingsize'])
rule([f'{s} :is({HEADINGS})'], ['font-size: var(--opt-hs);', 'line-height: var(--opt-hlh);'])
s = scope(G['textsize'])
rule([f'{s} :is({BODY})'], ['font-size: var(--opt-ts);', 'line-height: var(--opt-tlh);'])
rule([f'{s} :is({BODY}) :is({INLINE}, a:not(.button))'], ['font-size: inherit;', 'line-height: inherit;'])
s = scope(G['fontweight'])
rule([f'{s} :is({TEXT}, {SOFT_INLINE})'], ['font-weight: var(--opt-fw);'])
s = scope(G['fontstyle'])
rule([f'{s} :is({TEXT}, {SOFT_INLINE})'], ['font-style: var(--opt-fs);'])
s = scope(G['textcase'])
rule([f'{s} :is({TEXT}, {SOFT_INLINE})'], ['text-transform: var(--opt-tt);'])
s = scope(G['letterspacing'])
rule([f'{s} :is({TEXT}, {SOFT_INLINE})'], ['letter-spacing: var(--opt-ls);'])
s = scope(G['lineheight'])
rule([f'{s} :is({TEXT})'], ['line-height: var(--opt-lh);'])
s = scope(G['textcolor'])
rule([s, f'{s} :is({TEXT})'], ['color: var(--opt-tc);'])
rule([f'{s} :is({TEXT}) :is({INLINE})'], ['color: inherit;'])
s = scope(G['headingcolor'])
rule([f'{s} :is({HEADINGS})', f'{s} :is({HEADINGS}) :is({INLINE}, a:not(.button))'], ['color: var(--opt-hc);'])
links = ':is(' + ', '.join(f'.{cls(G[k], o)}' for k in ('textcolor', 'linkcolor') for o in options(G[k])) + '):not(#opt)'
rule([f'{links} a:not(.button)'], ['color: var(--opt-lc, var(--opt-tc));'])
s = scope(G['textalign'])
rule([s, f'{s} :is({TEXT})'], ['text-align: var(--opt-ta);'])

pos = G['position']
content = ', '.join(OVERLAY_CONTENT)
css.append('/* Content position (blocks with text over an image): the content box fills the block')
css.append('   inside a 24px / 48px safe area and places its text with flex alignment */')
rule([f"{scope(pos)} :is({content})"],
     ['position: absolute;', 'inset: 24px 20px;', 'display: flex;', 'flex-direction: column;',
      'max-width: none;', 'margin: 0;'])
for o in options(pos):
    rule([f'.{cls(pos, o)}:not(#opt) :is({content})'],
         [f'justify-content: {o[2]};', f'align-items: {o[3]};', f'text-align: {o[4]};'])
css.append('@media (width >= 900px) {')
css.append(f"  {scope(pos)} :is({content}) {{")
css.append('    inset: 48px max(calc((100% - var(--container)) / 2), 24px);')
css.append('  }')
css.append('}')
open(os.path.join(ROOT, 'styles/text-options.css'), 'w').write('\n'.join(css) + '\n')

# ---------------------------------------------------------------- JS
keys = [g['key'] for g in GROUPS if not g.get('overlay')]
prefixes = [f"{g['prefix']}-" for g in GROUPS]
open(os.path.join(ROOT, 'scripts/text-options.js'), 'w').write(
    '// GENERATED by tools/text-options/build.py from tools/text-options/options.json — do not edit.\n'
    '// Section metadata keys of the "Text style" tab (their values are option class names) and the\n'
    '// class prefixes of every text option.\n'
    f"export const SECTION_TEXT_OPTIONS = {json.dumps(keys)};\n"
    f"export const TEXT_OPTION_PREFIXES = {json.dumps(prefixes)};\n".replace('"', "'").replace("','", "', '"),
)
print(f'{len(changed)} model files, {sum(len(options(g)) for g in GROUPS)} options in {len(GROUPS)} groups')
